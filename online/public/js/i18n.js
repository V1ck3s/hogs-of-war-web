const STORE = 'cdg.online.lang';
function stored() { try { return localStorage.getItem(STORE); } catch { return null; } }
function browserLang() {
  for (const l of navigator.languages || [navigator.language || '']) {
    const base = String(l).toLowerCase().split('-')[0];
    if (DICT[base]) return base;
  }
  return 'en';
}
// ?lang=fr|en (tests, shared links) wins for this visit without being stored.
const forced = new URLSearchParams(location.search).get('lang');
let lang = DICT[forced] ? forced : DICT[stored()] ? stored() : browserLang();

export const getLang = () => lang;
export function t(key, ...args) {
  const v = DICT[lang][key] ?? DICT.en[key];
  if (v == null) return key;
  return typeof v === 'function' ? v(...args) : v;
}
export const has = (key) => DICT[lang][key] != null || DICT.en[key] != null;

const listeners = [];
export const onLangChange = (fn) => listeners.push(fn);
export function setLang(l) {
  if (!DICT[l] || l === lang) return;
  lang = l;
  try { localStorage.setItem(STORE, l); } catch { /* private mode */ }
  applyDom();
  for (const fn of listeners) fn(l);
}

// Static text: data-i18n (text), data-i18n-html (trusted markup from DICT),
// data-i18n-placeholder, data-i18n-title, data-i18n-aria-label, data-i18n-content,
// data-i18n-empty (what an empty list shows, see style.css).
export function applyDom(root = document) {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  for (const e of root.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n);
  for (const e of root.querySelectorAll('[data-i18n-html]')) e.innerHTML = t(e.dataset.i18nHtml);
  for (const a of ['placeholder', 'title', 'aria-label', 'content']) {
    const prop = `i18n${a.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('')}`;
    for (const e of root.querySelectorAll(`[data-i18n-${a}]`)) e.setAttribute(a, t(e.dataset[prop]));
  }
  for (const e of root.querySelectorAll('[data-i18n-empty]')) e.dataset.empty = t(e.dataset.i18nEmpty);
  for (const s of root.querySelectorAll('select.lang')) s.value = lang;
}
